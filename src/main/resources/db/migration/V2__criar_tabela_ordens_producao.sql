-- criar a tabela de ordens de produção vinculadas a um equipamento.
create table ordens_producao (

    -- identificador gerado pelo banco.
    id bigint generated by default as identity primary key,

    -- código único da ordem de produção.
    codigo varchar(50) not null unique,

    -- produto que está sendo fabricado.
    produto varchar(150) not null,

    -- quantidade planejada para fabricação.
    quantidade_planejada integer not null,

    -- quantidade já produzida.
    quantidade_produzida integer not null default 0,

    -- estado atual da ordem de produção.
    estado varchar(30) not null default 'CRIADA',

    -- chave estrangeira do equipamento onde a ordem é executada.
    equipamento_id bigint not null,

    constraint fk_ordens_producao_equipamento foreign key (equipamento_id) references equipamentos(id)
);
