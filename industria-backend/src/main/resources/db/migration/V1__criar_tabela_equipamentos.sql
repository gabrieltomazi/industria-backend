-- criar a tabela de equipamentos da fábrica.
create table equipamentos (

    -- cria uma chave numérica gerada automaticamente pelo postgresql.
    id bigint generated by default as identity primary key,

    -- nome do equipamento.
    nome varchar(100) not null,

    -- código único de fábrica.
    codigo varchar(50) not null unique,

    -- setor onde a máquina opera.
    setor varchar(100) not null,

    -- estado atual de operação da máquina.
    estado varchar(30) not null default 'ATIVO'
);
