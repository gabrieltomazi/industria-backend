-- criar a tabela de inspeções de qualidade vinculadas a uma ordem de produção.
create table inspecoes_qualidade (

    -- identificador gerado pelo banco.
    id bigint generated by default as identity primary key,
    
    -- chave estrangeira que referencia a ordem de produção inspecionada.
    ordem_producao_id bigint not null,

    -- quantidade de peças que foram inspecionadas.
    quantidade_inspecionada integer not null,

    -- quantidade de peças reprovadas no teste de qualidade.
    quantidade_reprovada integer not null default 0,

    -- data da realização do teste.
    data date not null,

    -- observações adicionais sobre o lote ou teste.
    observacoes varchar(255),

    constraint fk_inspecoes_qualidade_ordem foreign key (ordem_producao_id) references ordens_producao(id)
);

